from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath
from typing import Any

from .storage import BASE_DIR

WORKSPACE_ROOT = (BASE_DIR / "playground").resolve()
MAX_FILE_BYTES = 500_000
ALLOWED_SOURCE_EXTENSIONS = {
    ".html", ".css", ".js", ".py", ".json", ".md", ".txt", ".yml",
    ".yaml", ".toml", ".ini", ".sql", ".svg", ".xml", ".csv",
}
BLOCKED_NAMES = {"run.cmd", "run.bat", "start.cmd", "start.bat"}


def _slug(value: str) -> str:
    value = value.lower().strip()
    value = re.sub(r"[^a-z0-9]+", "-", value).strip("-")
    return (value or "project")[:48]


def _project_path(project_id: str) -> Path:
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,47}", project_id):
        raise ValueError("Invalid project ID")
    path = (WORKSPACE_ROOT / project_id).resolve()
    if path.parent != WORKSPACE_ROOT:
        raise ValueError("Invalid project path")
    return path


def _safe_relative_path(relative_path: str) -> Path:
    normalized = relative_path.replace("\\", "/")
    candidate = PurePosixPath(normalized)
    if not normalized or candidate.is_absolute() or any(part in {"", ".", ".."} for part in candidate.parts):
        raise ValueError("File path must be a safe relative path inside the project")
    if any(":" in part for part in candidate.parts):
        raise ValueError("Drive-qualified paths are not allowed")
    return Path(*candidate.parts)


def create_project(title: str, project_id: str | None = None) -> dict[str, Any]:
    WORKSPACE_ROOT.mkdir(parents=True, exist_ok=True)
    base_id = _slug(project_id or title)
    safe_id = base_id
    suffix = 2
    while _project_path(safe_id).exists():
        safe_id = f"{base_id[:43]}-{suffix}"
        suffix += 1
    root = _project_path(safe_id)
    (root / "tests").mkdir(parents=True)
    manifest = {
        "id": safe_id,
        "title": title[:160],
        "created_at": datetime.now(timezone.utc).isoformat(),
        "status": "created",
    }
    (root / "project.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def list_projects() -> list[dict[str, Any]]:
    if not WORKSPACE_ROOT.exists():
        return []
    result = []
    for path in sorted(WORKSPACE_ROOT.iterdir()):
        manifest_path = path / "project.json"
        if path.is_dir() and manifest_path.is_file():
            try:
                result.append(json.loads(manifest_path.read_text(encoding="utf-8")))
            except (OSError, json.JSONDecodeError):
                continue
    return result


def project_file_path(project_id: str, relative_path: str, *, for_write: bool = False) -> Path:
    root = _project_path(project_id)
    if not root.is_dir():
        raise FileNotFoundError(f"Project not found: {project_id}")
    rel = _safe_relative_path(relative_path)
    if for_write:
        if rel.name.lower() in BLOCKED_NAMES:
            raise ValueError("Run scripts are generated by the workspace manager, not by an agent")
        if rel.suffix.lower() not in ALLOWED_SOURCE_EXTENSIONS:
            raise ValueError(f"File extension is not allowed: {rel.suffix or '(none)'}")
    target = (root / rel).resolve()
    if root not in target.parents:
        raise ValueError("File path escapes the project directory")
    return target


def write_project_file(project_id: str, relative_path: str, content: str, *, allowed_extensions: set[str] | None = None) -> dict[str, Any]:
    path = project_file_path(project_id, relative_path, for_write=True)
    if allowed_extensions is not None and path.suffix.lower() not in allowed_extensions:
        raise ValueError(f"This agent cannot write {path.suffix or 'extensionless'} files")
    encoded = content.encode("utf-8")
    if len(encoded) > MAX_FILE_BYTES:
        raise ValueError(f"File is too large (limit {MAX_FILE_BYTES} bytes)")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded)
    return {"path": relative_path.replace("\\", "/"), "bytes": len(encoded)}


def read_project_file(project_id: str, relative_path: str) -> str:
    path = project_file_path(project_id, relative_path)
    if not path.is_file():
        raise FileNotFoundError(f"File not found: {relative_path}")
    if path.stat().st_size > MAX_FILE_BYTES:
        raise ValueError("File is too large to read through the API")
    return path.read_text(encoding="utf-8")


def list_project_files(project_id: str) -> list[dict[str, Any]]:
    root = _project_path(project_id)
    if not root.is_dir():
        raise FileNotFoundError(f"Project not found: {project_id}")
    files = []
    for path in root.rglob("*"):
        if not path.is_file() or any(part in {".git", "__pycache__", ".venv", "venv", "node_modules"} for part in path.parts):
            continue
        relative = path.relative_to(root).as_posix()
        files.append({"path": relative, "bytes": path.stat().st_size})
    return sorted(files, key=lambda item: item["path"])


def generate_run_cmd(project_id: str) -> str:
    root = _project_path(project_id)
    if not root.is_dir():
        raise FileNotFoundError(f"Project not found: {project_id}")
    if (root / "server.py").is_file():
        contents = "@echo off\r\nsetlocal\r\ncd /d \"%~dp0\"\r\npython server.py\r\nset EXIT_CODE=%ERRORLEVEL%\r\necho.\r\necho Application exited with code %EXIT_CODE%.\r\npause\r\nexit /b %EXIT_CODE%\r\n"
    elif (root / "index.html").is_file():
        contents = "@echo off\r\nsetlocal\r\ncd /d \"%~dp0\"\r\nstart \"\" \"%~dp0index.html\"\r\n"
    else:
        contents = "@echo off\r\necho No supported entry point was found. Add index.html or server.py.\r\npause\r\nexit /b 1\r\n"
    target = root / "run.cmd"
    target.write_text(contents, encoding="utf-8")
    return "run.cmd"


def run_project_checks(project_id: str, timeout_seconds: int = 60) -> dict[str, Any]:
    """Run fixed, local checks; never accepts an arbitrary command from an LLM or API caller."""
    root = _project_path(project_id)
    if not root.is_dir():
        raise FileNotFoundError(f"Project not found: {project_id}")
    results: list[dict[str, Any]] = []

    python_files = [p for p in root.rglob("*.py") if p.is_file() and not _is_ignored(p, root)]
    for path in python_files:
        rel = path.relative_to(root).as_posix()
        completed = subprocess.run(
            [sys.executable, "-m", "py_compile", str(path)], cwd=str(root),
            capture_output=True, text=True, timeout=timeout_seconds, shell=False,
        )
        results.append(_command_result(f"Python syntax: {rel}", completed))

    node = shutil.which("node")
    js_files = [p for p in root.rglob("*.js") if p.is_file() and not _is_ignored(p, root)]
    if js_files and node:
        for path in js_files:
            rel = path.relative_to(root).as_posix()
            completed = subprocess.run(
                [node, "--check", str(path)], cwd=str(root),
                capture_output=True, text=True, timeout=timeout_seconds, shell=False,
            )
            results.append(_command_result(f"JavaScript syntax: {rel}", completed))
    elif js_files:
        results.append({"check": "JavaScript syntax", "status": "skipped", "output": "Node.js is not installed or not on PATH."})

    tests_dir = root / "tests"
    test_files = list(tests_dir.glob("test*.py")) if tests_dir.is_dir() else []
    if test_files:
        completed = subprocess.run(
            [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"],
            cwd=str(root), capture_output=True, text=True, timeout=timeout_seconds, shell=False,
        )
        results.append(_command_result("Python unit tests", completed))

    if not results:
        results.append({"check": "Project checks", "status": "skipped", "output": "No supported Python or JavaScript files were found for static checks."})
    failed = any(item["status"] == "failed" for item in results)
    return {
        "project_id": project_id,
        "status": "failed" if failed else ("passed" if any(x["status"] == "passed" for x in results) else "skipped"),
        "checks": results,
        "finished_at": datetime.now(timezone.utc).isoformat(),
    }


def _is_ignored(path: Path, root: Path) -> bool:
    return any(part in {".git", "__pycache__", ".venv", "venv", "node_modules"} for part in path.relative_to(root).parts)


def _command_result(label: str, completed: subprocess.CompletedProcess[str]) -> dict[str, Any]:
    output = (completed.stdout or "") + (completed.stderr or "")
    return {
        "check": label,
        "status": "passed" if completed.returncode == 0 else "failed",
        "exit_code": completed.returncode,
        "output": output[-12000:],
    }
